import type { ReactNode, FormEvent } from "react";
import { useQuery } from "@tanstack/react-query";
import { ArrowUpRight, BookOpen, BrainCircuit, FileText, FolderKanban, Plus, Sparkles } from "lucide-react";
import { Link } from "react-router-dom";
import { useState } from "react";
import { projectsApi } from "../api/projects";
import { Modal } from "../components/Modal";
import { StatusPill } from "../components/StatusPill";
import type { Project } from "../types";

export function Dashboard() {
  const [showCreate, setShowCreate] = useState(false);
  const { data: projects = [], isLoading, error } = useQuery({ queryKey: ["projects"], queryFn: projectsApi.list });
  const recent = [...projects].slice(0, 5);

  return <div className="page">
    <div className="welcome-row">
      <div><div className="eyebrow">YOUR RESEARCH COMMAND CENTER</div><h1>Good morning, researcher <span className="wave">✦</span></h1><p className="muted">Turn complex questions into structured, evidence-backed research.</p></div>
      <button className="btn primary" onClick={() => setShowCreate(true)}><Plus size={17} /> New project</button>
    </div>
    <section className="hero-card">
      <div className="hero-copy"><div className="hero-tag"><Sparkles size={14} /> YOUR AI RESEARCH WORKSPACE</div><h2>Think deeper.<br /><em>Discover more.</em></h2><p>Bring your documents, research plans and AI assistant together in one focused workspace.</p><button className="btn light" onClick={() => setShowCreate(true)}>Start a research project <ArrowUpRight size={16} /></button></div>
      <div className="hero-art"><div className="orbit orbit-one" /><div className="orbit orbit-two" /><div className="orb-core"><BrainCircuit size={48} /></div><div className="float-card float-top"><Sparkles size={15} /> Planner agent <span className="live-dot" /></div><div className="float-card float-bottom"><FileText size={15} /> Document intelligence</div></div>
    </section>
    <div className="section-heading"><div><h2>Workspace overview</h2><p className="muted">A snapshot of your research activity</p></div></div>
    <div className="stats-grid">
      <Stat icon={<FolderKanban />} label="Research projects" value={projects.length} note="Across your workspace" />
      <Stat icon={<FileText />} label="Documents" value="—" note="Available inside projects" />
      <Stat icon={<BookOpen />} label="Research plans" value="—" note="Generated by your planner" />
    </div>
    <div className="section-heading projects-heading"><div><h2>Recent projects</h2><p className="muted">Pick up where you left off</p></div><Link to="/projects" className="text-link">View all <ArrowUpRight size={15} /></Link></div>
    {isLoading ? <div className="empty-state">Loading your projects…</div> : error ? <div className="error-box">{(error as Error).message}</div> : recent.length ? <div className="project-grid">{recent.map((project: Project, i) => <ProjectCard key={project._id} project={project} index={i} />)}</div> : <div className="empty-state"><div className="empty-icon"><FolderKanban /></div><h3>Your research starts here</h3><p>Create your first project to organize documents, generate a research plan and ask questions with AI.</p><button className="btn primary" onClick={() => setShowCreate(true)}><Plus size={16} /> Create first project</button></div>}
    {showCreate && <CreateProjectModal onClose={() => setShowCreate(false)} />}
  </div>;
}

function Stat({ icon, label, value, note }: { icon: ReactNode; label: string; value: React.ReactNode; note: string }) {
  return <div className="stat-card"><div className="stat-icon">{icon}</div><div className="stat-label">{label}</div><div className="stat-value">{value}</div><div className="stat-note">{note}</div></div>;
}

function ProjectCard({ project, index }: { project: Project; index: number }) {
  const colors = ["violet", "blue", "mint", "amber"];
  return <Link to={`/projects/${project._id}`} className="project-card"><div className={`project-symbol ${colors[index % colors.length]}`}><FolderKanban size={19} /></div><div className="project-card-top"><StatusPill status={project.status || "active"} /><ArrowUpRight size={16} className="subtle-icon" /></div><h3>{project.title}</h3><p>{project.objective || project.description || "No project objective provided yet."}</p><div className="project-card-foot"><span>{project.createdAt ? new Date(project.createdAt).toLocaleDateString() : "Research project"}</span><span className="mini-avatar">R</span></div></Link>;
}

function CreateProjectModal({ onClose }: { onClose: () => void }) {
  const [title, setTitle] = useState("");
  const [objective, setObjective] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const query = useQuery({ queryKey: ["projects"], queryFn: projectsApi.list, enabled: false });
  async function submit(e: FormEvent) {
    e.preventDefault(); setBusy(true); setError("");
    try { await projectsApi.create({ title, objective }); await query.refetch(); window.location.href = "/"; }
    catch (err) { setError((err as Error).message); setBusy(false); }
  }
  return <Modal title="Create a research project" onClose={onClose}><form className="form-stack" onSubmit={submit}><label>Project name<input required minLength={3} value={title} onChange={e => setTitle(e.target.value)} placeholder="e.g. UK Property Management Research" /></label><label>Research objective<textarea required minLength={10} rows={4} value={objective} onChange={e => setObjective(e.target.value)} placeholder="What are you trying to discover?" /></label>{error && <div className="error-box">{error}</div>}<div className="modal-actions"><button type="button" className="btn ghost" onClick={onClose}>Cancel</button><button className="btn primary" disabled={busy}>{busy ? "Creating…" : "Create project"}</button></div></form></Modal>;
}
